import numpy as np
import pandas as pd
import difflib
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

movies = pd.read_csv("movies.csv", on_bad_lines='skip')

movies.head()

movies.info()

movies.describe()

movies.describe()

selected_features = ['genres','keywords','tagline','cast','director']

for feature in selected_features:
    movies[feature] = movies[feature].fillna('')

combined_features = (
    movies['genres'] + ' ' +
    movies['keywords'] + ' ' +
    movies['tagline'] + ' ' +
    movies['cast'] + ' ' +
    movies['director']
)

vectorizer = TfidfVectorizer(stop_words='english')

feature_vectors = vectorizer.fit_transform(combined_features)

similarity = cosine_similarity(feature_vectors)

movie_name = input("Enter your favourite movie: ")

movie_list = movies['title'].tolist()

import difflib

find_close_match = difflib.get_close_matches(movie_name, movie_list)

close_match = find_close_match[0]

index = movies[movies.title == close_match].index[0]

similarity_score = list(enumerate(similarity[index]))

sorted_movies = sorted(similarity_score, key=lambda x:x[1], reverse=True)

print("Movies Suggested for You:\n")

i = 1

for movie in sorted_movies:
    movie_index = movie[0]
    title = movies.iloc[movie_index]['title']

    if i <= 20:
        print(i, ".", title)
        i += 1

